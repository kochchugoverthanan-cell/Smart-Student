const DICT: Record<Lang, Record<string, string>> = { en: {}, ta: {}, si: {} };
for (const [k, en, ta, si] of ROWS) { DICT.en[k] = en; DICT.ta[k] = ta; DICT.si[k] = si; }

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = DICT[lang][key] ?? DICT.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Returns t(key, vars): text in the student's chosen interface language (falls back to English). */
export function useT() {
  const lang = useSettings((s) => s.language);
  return useCallback((key: string, vars?: Record<string, string | number>) => translate(lang, key, vars), [lang]);
}
